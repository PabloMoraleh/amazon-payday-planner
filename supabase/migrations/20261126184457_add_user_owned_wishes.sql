create table public.wishes (
    id                 bigint generated by default as identity primary key,
    user_id            uuid not null default auth.uid()
                                references auth.users (id) on delete cascade,
    name               text not null,
    url                text,
    store              text not null default 'Amazon',
    asin               text,
    price_cents        integer not null check (price_cents >= 0),
    currency           text not null default 'EUR' check (char_length(currency) = 3),
    priority           integer not null default 2 check (priority between 1 and 3),
    notes              text,
    status             text not null default 'wanted'
                                check (status in ('wanted', 'bought', 'dropped')),
    track_price        boolean not null default false,
    target_price_cents integer check (target_price_cents >= 0),
    bought_price_cents integer check (bought_price_cents >= 0),
    bought_at          timestamptz,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now()
);

create table public.price_history (
    id          bigint generated by default as identity primary key,
    wish_id     bigint not null references public.wishes (id) on delete cascade,
    price_cents integer not null check (price_cents >= 0),
    currency    text not null default 'EUR' check (char_length(currency) = 3),
    source      text not null default 'manual' check (source in ('manual', 'tracker')),
    recorded_at timestamptz not null default now()
);

create table public.budgets (
    id           bigint generated by default as identity primary key,
    user_id      uuid not null default auth.uid()
                         references auth.users (id) on delete cascade,
    month        text not null check (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    amount_cents integer not null check (amount_cents >= 0),
    currency     text not null default 'EUR' check (char_length(currency) = 3),
    payday       date,
    unique (user_id, month)
);

create index wishes_user_status_priority_created_idx
    on public.wishes (user_id, status, priority, created_at);
create index price_history_wish_recorded_idx
    on public.price_history (wish_id, recorded_at desc);

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger wishes_set_updated_at
before update on public.wishes
for each row execute function public.set_updated_at();

alter table public.wishes enable row level security;
alter table public.price_history enable row level security;
alter table public.budgets enable row level security;

grant select, insert, update, delete on public.wishes to authenticated;
grant select, insert, update, delete on public.price_history to authenticated;
grant select, insert, update, delete on public.budgets to authenticated;
grant usage on schema public to authenticated;
grant usage, select on sequence
    public.wishes_id_seq,
    public.price_history_id_seq,
    public.budgets_id_seq
to authenticated;

create policy "Users can read their own wishes"
    on public.wishes for select to authenticated
    using (user_id = (select auth.uid()));
create policy "Users can add their own wishes"
    on public.wishes for insert to authenticated
    with check (user_id = (select auth.uid()));
create policy "Users can update their own wishes"
    on public.wishes for update to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));
create policy "Users can delete their own wishes"
    on public.wishes for delete to authenticated
    using (user_id = (select auth.uid()));

create policy "Users can read price history for their wishes"
    on public.price_history for select to authenticated
    using (exists (
        select 1 from public.wishes
        where wishes.id = price_history.wish_id
          and wishes.user_id = (select auth.uid())
    ));
create policy "Users can add price history for their wishes"
    on public.price_history for insert to authenticated
    with check (exists (
        select 1 from public.wishes
        where wishes.id = price_history.wish_id
          and wishes.user_id = (select auth.uid())
    ));
create policy "Users can update price history for their wishes"
    on public.price_history for update to authenticated
    using (exists (
        select 1 from public.wishes
        where wishes.id = price_history.wish_id
          and wishes.user_id = (select auth.uid())
    ))
    with check (exists (
        select 1 from public.wishes
        where wishes.id = price_history.wish_id
          and wishes.user_id = (select auth.uid())
    ));
create policy "Users can delete price history for their wishes"
    on public.price_history for delete to authenticated
    using (exists (
        select 1 from public.wishes
        where wishes.id = price_history.wish_id
          and wishes.user_id = (select auth.uid())
    ));

